"""Import MemProcFS FindEvil indicator types and their false-positive ratings from the pinned wiki page.

Part 12 FM-6 (operator decision 2026-10-28): FindEvil verdicts are ranked by the rating MemProcFS itself
documents for each type, never by a typed list. The page is pinned by its wiki commit and SHA-256; a changed
page or a type section without a rating stops the import.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
WIKI = "MemProcFS.wiki"
VERSION = "b975278259ed35464799e519ad45e20260784b1b"
PAGE = "FS_FindEvil.md"
PAGE_SHA256 = "1dd605f882fa739781afd4d4d4320952ca7597b0f58acd9e3d54acc1251ac7cd"
SNAPSHOT = HERE / "pinned" / "memprocfs_findevil" / WIKI / VERSION / PAGE
OUT = REPO / "src" / "nexus" / "data" / "knowledge" / "sources" / "memprocfs_findevil.yaml"
SOURCE = f"https://github.com/ufrisk/MemProcFS/wiki/FS_FindEvil (wiki commit {VERSION})"
RATINGS = ("LOW", "MEDIUM", "HIGH")

_HEADER = re.compile(r"^\|\s*`([A-Z_*]+)`\s*\|\s*(.*?)\s*\|\s*$")
_SEPARATOR = re.compile(r"^\|\s*-{3,}")
_FP_ROW = re.compile(r"^\|\s*False&nbsp;Positives:\s*\|\s*(.*?)\s*\|\s*$")
_SUBTYPE = re.compile(r"^\|\s*`(YR_[A-Z_]+)`\s*\|\s*(.*?)\s*\|\s*$")


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse(text: str) -> dict[str, dict[str, str]]:
    """Every indicator type section with its rating; YR_ sub-types inherit the YR_* section's rating."""
    lines = text.splitlines()
    types: dict[str, dict[str, str]] = {}
    current = ""
    for index, line in enumerate(lines):
        header = _HEADER.match(line)
        if header and index + 1 < len(lines) and _SEPARATOR.match(lines[index + 1]):
            current = header.group(1)
            types[current] = {"title": header.group(2), "fp": "", "note": ""}
            continue
        fp_row = _FP_ROW.match(line)
        if fp_row and current:
            value = fp_row.group(1)
            rating = value.split(":", 1)[0].strip().upper()
            if rating not in RATINGS:
                raise ValueError(f"{current}: no LOW/MEDIUM/HIGH rating in {value!r}")
            note = value.split(":", 1)[1].strip() if ":" in value else ""
            types[current].update(fp=rating, note=note)
            continue
        sub = _SUBTYPE.match(line)
        if sub and current == "YR_*":
            types[sub.group(1)] = {"title": sub.group(2), "fp": "", "note": "", "inherits": "YR_*"}
    for entry in types.values():
        if entry.get("inherits"):
            parent = types[entry["inherits"]]
            entry.update(fp=parent["fp"], note=parent["note"])
    unrated = sorted(name for name, entry in types.items() if not entry["fp"])
    if unrated:
        raise ValueError(f"type sections without a rating: {unrated}")
    return types


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify the output is current; write nothing")
    args = ap.parse_args(argv)
    if not SNAPSHOT.is_file():
        raise SystemExit(f"pinned source is missing: {SNAPSHOT}")
    actual = _sha256(SNAPSHOT)
    if actual != PAGE_SHA256:
        raise SystemExit(f"pinned source hash changed: {PAGE}: {actual}")
    types = parse(SNAPSHOT.read_text(encoding="utf-8"))
    doc = {
        "version": 1,
        "generator": "devtools/knowledge/import_memprocfs_findevil.py",
        "description": "MemProcFS FindEvil indicator types and the false-positive rating the MemProcFS wiki "
                       "documents for each; regenerate from the pinned snapshot.",
        "source_manifest": [{"source": SOURCE, "source_version": VERSION, "source_key": PAGE,
                             "source_sha256": PAGE_SHA256}],
        "types": {name: types[name] for name in sorted(types)},
    }
    text = ("# Generated by devtools/knowledge/import_memprocfs_findevil.py. Do not edit by hand.\n"
            + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=120))
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT} is stale; run the importer")
            return 1
        print("memprocfs_findevil.yaml is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(types)} types)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
