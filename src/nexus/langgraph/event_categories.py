"""Which pinned category an event id belongs to, per provider (operator decision 2026-10-12).

The table is generated by ``devtools/knowledge/import_event_categories.py`` from the pinned
pySigma pipelines, and this module reads it. An event with no entry has no pinned category.

A row with no pinned category takes the category of its family and file (``family_categories.yaml``,
D112). A rule that ``requires`` a subject applies only to rows that name it (D117, 2026-10-13). Otherwise the
row is ``OTHER``: the pinned sources define no logon category, so logons are ``OTHER`` until a pinned source
for them is added.
"""
from __future__ import annotations

import fnmatch
import re
from functools import lru_cache
from pathlib import Path

import yaml

OTHER = "other"

_TABLE = Path(__file__).resolve().parents[1] / "data" / "schema" / "event_categories.yaml"
_FAMILY_TABLE = Path(__file__).resolve().parents[1] / "data" / "schema" / "family_categories.yaml"

#: What the logs write for "nothing here". Observed in the case index (2026-10-12): `-\-` is an empty subject
#: account, `%%1833` is an unresolved message code, `S-1-0-0` is the null SID. A listening socket names its foreign end
#: as the unspecified address (0.0.0.0 or ::) or, in Volatility's netscan, as `*` (D117, 2026-10-13). None is a destination.
#: `(none)` is Task Scheduler's user context for a task that ran with none (D214).
PLACEHOLDERS = frozenset({"", "-", "-\\-", "n/a", "(null)", "(none)", "s-1-0-0", "0.0.0.0", "::", "::0", "*"})
_MESSAGE_CODE = re.compile(r"%%\d+")


def present(value: object) -> str:
    """The value as text, or ``""`` when it is a placeholder the logs write for 'nothing here'."""
    text = str(value if value is not None else "").strip()
    if text.lower() in PLACEHOLDERS or _MESSAGE_CODE.fullmatch(text):
        return ""
    return text


@lru_cache(maxsize=1)
def _doc() -> dict:
    return yaml.safe_load(_TABLE.read_text(encoding="utf-8")) or {}


@lru_cache(maxsize=1)
def _table() -> dict[tuple[str, str], str]:
    return {
        (str(e["provider"]), str(e["event_id"])): str(e["category"])
        for e in _doc().get("entries") or []
    }


@lru_cache(maxsize=1)
def _channel_owners() -> dict[tuple[str, str], str]:
    return {(str(r["channel"]), str(r["event_id"])): str(r["provider"]) for r in _doc().get("channels") or []}


def provider_for(channel: object, event_id: object) -> str:
    """The provider that logs (channel, event id), as its pinned manifest declares; '' when none does.

    For a row that names only its channel, Hayabusa's timeline among them (D232).
    """
    return _channel_owners().get((str(channel or "").strip(), str(event_id or "").strip()), "")


def category_for(provider: object, event_id: object) -> str:
    """The pinned category of (provider, event id), or ``other``.

    The provider is part of the key: Sysmon's ids 1 to 29 are not unique across providers.
    """
    key = (str(provider or "").strip(), str(event_id or "").strip())
    return _table().get(key, OTHER)


def known_categories() -> frozenset[str]:
    """Every category the pinned table names."""
    return frozenset(_table().values())


@lru_cache(maxsize=1)
def _family_rules() -> tuple[tuple[str, str | None, str, tuple[str, ...]], ...]:
    """``(family, glob or None, category, requires)`` in match order: rules with a glob first, then the family rules."""
    doc = yaml.safe_load(_FAMILY_TABLE.read_text(encoding="utf-8")) or {}
    rules = []
    for r in doc.get("rules") or []:
        requires = tuple(str(k).strip() for k in (r.get("requires") or []) if str(k).strip())
        rules.append((
            str(r["family"]).strip().lower(),
            str(r["glob"]).strip().lower() if r.get("glob") else None,
            str(r["category"]),
            requires,
        ))
    return tuple(sorted(rules, key=lambda rule: rule[1] is None))


def family_category(source: object, row: dict | None = None) -> str:
    """The category a row's family and file give, or ``other``.

    ``source`` is the evidence row's ``family/file`` (``evidence_rows.evidence_rows_for_hits``). A rule with
    ``requires`` classifies the row only when the row carries each named subject (a row key such as
    ``destination_ip``). A row that names none of them stays ``other`` rather than falling back to the host.
    """
    family, _, file = str(source or "").partition("/")
    family, file = family.strip().lower(), file.strip().lower()
    for rule_family, glob, category, requires in _family_rules():
        if rule_family != family or (glob is not None and not fnmatch.fnmatchcase(file, glob)):
            continue
        if requires and not all(present((row or {}).get(key)) for key in requires):
            continue
        return category
    return OTHER


def row_category(row: dict) -> str:
    """The category of one evidence row: its pinned category, else its family's, else ``other``."""
    pinned = category_for(row.get("provider"), row.get("event_id"))
    return pinned if pinned != OTHER else family_category(row.get("source"), row)


def family_categories() -> frozenset[str]:
    """Every category the family table names."""
    return frozenset(category for _, _, category, _ in _family_rules())
